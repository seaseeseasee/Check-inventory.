-- 013: บังคับเปลี่ยนรหัสผ่านเมื่อเข้าสู่ระบบครั้งแรก
--
--   บัญชีพยาบาลใหม่: ชื่อผู้ใช้ = เบอร์โทรศัพท์ (ตัวเลขล้วน เช่น 0812345678)
--                    รหัสผ่านเริ่มต้น = เบอร์โทรศัพท์เดียวกัน
--   must_change_password = 1 → เข้าสู่ระบบได้ แต่ใช้งานได้เฉพาะหน้า "เปลี่ยนรหัสผ่าน" จนกว่าจะเปลี่ยนสำเร็จ
--     ตั้งเป็น 1 เมื่อ: สร้างบัญชี / admin ตั้งรหัสผ่านใหม่ให้ / ตรวจพบว่ายังใช้รหัสผ่าน = ชื่อผู้ใช้
--     ตั้งเป็น 0 เมื่อ: ผู้ใช้เปลี่ยนรหัสผ่านเองสำเร็จ
--
-- บัญชีเดิมไม่ถูกบังคับ (ค่าเริ่มต้น 0) ยกเว้นบัญชีที่รหัสผ่านยังเท่ากับชื่อผู้ใช้ — ระบบจับได้ตอน login
-- รันซ้ำได้
-- ============================================================================

ALTER TABLE refer_users
  ADD COLUMN IF NOT EXISTS must_change_password TINYINT(1) NOT NULL DEFAULT 0
    COMMENT '1 = ต้องเปลี่ยนรหัสผ่านก่อนใช้งาน (รหัสเริ่มต้น/รหัสที่ admin ตั้งให้)' AFTER password_hash,
  ADD COLUMN IF NOT EXISTS password_changed_at VARCHAR(40) NULL
    COMMENT 'เวลาที่ผู้ใช้เปลี่ยนรหัสผ่านเองล่าสุด' AFTER must_change_password;
